"""
combine_core.py
Core logic (no UI) for combining any sheet (by name) of many Excel files.

- Header (Row 1) kept once; columns A..AZ by default, or all columns.
- Values only (Excel cached results). If a Chart file's Mapping sheet has no
  cached values (generated by script, never saved in Excel), it is
  recalculated from the RawData sheet.
- Columns can be matched by header name, exact duplicate rows can be removed.
- Can append new rows below an existing (previously combined) Excel file.
- Several sheets can be combined at once -> one output sheet each.
"""
import re
from io import BytesIO

import openpyxl
from openpyxl.cell import WriteOnlyCell
from openpyxl.styles import Font
from openpyxl.utils import column_index_from_string, get_column_letter


# ---------------------------------------------------------------- helpers
def parse_cols(rng: str):
    """'A:AZ' -> (1, 52); '' or 'ALL' -> (1, None) = all used columns."""
    s = (rng or "").upper().replace(" ", "")
    if s in ("", "ALL"):
        return 1, None
    a, b = s.split(":")
    return column_index_from_string(a), column_index_from_string(b)


def is_formula(v):
    return isinstance(v, str) and v.startswith("=")


def row_empty(row):
    return all(v is None or (isinstance(v, str) and v.strip() == "") for v in row)


def _trim(rows):
    while rows and row_empty(rows[-1]):
        rows.pop()
    return rows


# ------------------------------------------------- fallback recalculation
_RE_RAWREF = re.compile(r"^=RawData!\$?([A-Z]+)\$?(\d+)$")                       # =RawData!A2
_RE_IFRAW = re.compile(r'^=IF\(RawData!\$?([A-Z]+)\$?(\d+)="","",RawData!\$?\1\$?\2\)$')  # =IF(RawData!$B$2="","",..)
_RE_SUMIFS = re.compile(r"SUMIFS\(RawData!\$?([A-Z]+):\$?[A-Z]+,(.*)\)\)$")       # target column + criteria
_RE_CRIT = re.compile(r'RawData!\$?([A-Z]+):\$?[A-Z]+,("([^"]*)"&)?\$?([A-Z]+)\$?\d+')
_RE_DIFF = re.compile(r"^=([A-Z]+)(\d+)-([A-Z]+)(\d+)$")                          # =G3-G2
_RE_ARITH = re.compile(r"^[0-9+\-*/(). ,]*$")


def _eval_row_formula(f, n):
    """Evaluate ROW()-based arithmetic: =MOD(INT((ROW()-2)/31),4)+1, =100+10*MOD(ROW()-2,31) ..."""
    expr = f[1:].replace("ROW()", str(n)).replace("MOD(", "_mod(").replace("INT(", "_int(")
    if not _RE_ARITH.match(expr.replace("_mod", "").replace("_int", "")):
        return None
    return eval(expr, {"__builtins__": {}}, {"_mod": lambda a, b: a % b, "_int": lambda x: int(x // 1)})


def _recalc_mapping(wb_f, sheet, c1, c2):
    """Recompute Mapping values from RawData by interpreting the Mapping formulas
    (works for any current range / step / extra SUMIFS columns, e.g. 80-400mA or 100-400mA)."""
    raw = wb_f["RawData"]
    raw_rows = list(raw.iter_rows(values_only=True))           # raw_rows[0] = Excel row 1
    def rv(col, r):
        i, j = r - 1, column_index_from_string(col) - 1
        return raw_rows[i][j] if i < len(raw_rows) and j < len(raw_rows[i]) else None

    sum_cache = {}                                             # (target, critcols) -> {key: sum}
    def lookup(target, crit_cols, key):
        ck = (target, crit_cols)
        if ck not in sum_cache:
            ti = column_index_from_string(target) - 1
            ci = [column_index_from_string(c) - 1 for c in crit_cols]
            d = {}
            for r in raw_rows[1:]:
                k = tuple(r[i] for i in ci)
                v = r[ti]
                d[k] = d.get(k, 0) + (v if isinstance(v, (int, float)) else 0)
                d.setdefault(("__n__",) + k, True)
            sum_cache[ck] = d
        d = sum_cache[ck]
        return d.get(key, "") if ("__n__",) + key in d else ""

    out, done = [], {}                                         # done[(col_letter, row)] = value
    for i, frow in enumerate(wb_f[sheet].iter_rows(min_row=2, min_col=c1, max_col=c2, values_only=True)):
        if row_empty(frow):
            break
        n = i + 2
        row = []
        for j, f in enumerate(frow):
            col = get_column_letter(c1 + j)
            val = f
            if is_formula(f):
                f = f.replace(" ", "")
                val = None
                if m := _RE_RAWREF.match(f):
                    val = rv(m[1], int(m[2]))
                elif m := _RE_IFRAW.match(f):
                    v = rv(m[1], int(m[2]))
                    val = "" if v in (None, "") else v
                elif m := _RE_SUMIFS.search(f):
                    crits = _RE_CRIT.findall(m[2])
                    crit_cols = tuple(c[0] for c in crits)
                    key = tuple((c[2] + str(done.get((c[3], n), ""))) if c[1] else done.get((c[3], n))
                                for c in crits)
                    val = lookup(m[1], crit_cols, key)
                elif m := _RE_DIFF.match(f):
                    a, b = done.get((m[1], int(m[2]))), done.get((m[3], int(m[4])))
                    a = 0 if a in ("", None) else a
                    b = 0 if b in ("", None) else b
                    val = a - b
                elif "ROW()" in f:
                    val = _eval_row_formula(f, n)
            done[(col, n)] = val
            row.append(val)
        out.append(row)
    return out


_RE_HDR = re.compile(r'^=RawData!\$?A\$?2&"-?([^"]*)"$')   # =RawData!A2&"-Case_Temp"


def _clean_header(header, formula_header):
    """'48226H40040-Case_Temp' (SN of the first file) -> 'Case_Temp'."""
    out = list(header)
    for j, f in enumerate(formula_header[:len(out)]):
        if is_formula(f) and (m := _RE_HDR.match(f.replace(" ", ""))):
            out[j] = m[1]
    return out


# ---------------------------------------------------------------- readers
def list_sheets(data: bytes):
    """Sheet names of a workbook (fast, read-only)."""
    wb = openpyxl.load_workbook(BytesIO(data), read_only=True)
    names = list(wb.sheetnames)
    wb.close()
    return names


def read_sheet(data: bytes, sheet="Mapping", cols="A:AZ"):
    """Read one sheet (values). Returns (header, rows, note)."""
    c1, c2 = parse_cols(cols)
    wb_v = openpyxl.load_workbook(BytesIO(data), data_only=True, read_only=True)
    if sheet not in wb_v.sheetnames:
        wb_v.close()
        raise ValueError(f"sheet '{sheet}' not found (sheets: {', '.join(wb_v.sheetnames)})")
    rows = _trim([list(r) for r in wb_v[sheet].iter_rows(min_col=c1, max_col=c2, values_only=True)])
    wb_v.close()
    if not rows:
        raise ValueError("empty sheet")
    w = used_width(rows[0], rows[1:])                  # drop empty columns on the right
    header, body = rows[0][:w], [r[:w] for r in rows[1:]]

    note = ""
    # formulas of row 1-2 only (fast, read-only)
    wb_p = openpyxl.load_workbook(BytesIO(data), read_only=True)
    top = [list(r) for r in wb_p[sheet].iter_rows(min_row=1, max_row=2, min_col=c1, max_col=c2, values_only=True)]
    has_raw = "RawData" in wb_p.sheetnames
    wb_p.close()
    header = _clean_header(header, top[0] if top else [])
    probe = top[1] if len(top) > 1 else []
    no_cache = body and any(is_formula(f) for f in probe) and all(
        body[0][j] is None for j, f in enumerate(probe) if is_formula(f))
    if no_cache:
        if has_raw:
            wb_f = openpyxl.load_workbook(BytesIO(data))     # full load only when needed
            body = _recalc_mapping(wb_f, sheet, c1, c2)
            wb_f.close()
            note = "recalculated from RawData (no Excel cache)"
        else:
            note = "formulas have no saved values (open & save the file in Excel first)"
    return header, body, note


read_mapping = read_sheet   # backward compatible name


def read_table(data: bytes, cols="A:AZ", sheet=None):
    """Read an already-combined file (first sheet, or 'Combine' if present)."""
    c1, c2 = parse_cols(cols)
    wb = openpyxl.load_workbook(BytesIO(data), data_only=True, read_only=True)
    name = sheet or ("Combine" if "Combine" in wb.sheetnames else wb.sheetnames[0])
    rows = _trim([list(r) for r in wb[name].iter_rows(min_col=c1, max_col=c2, values_only=True)])
    wb.close()
    if not rows:
        raise ValueError("empty sheet")
    w = used_width(rows[0], rows[1:])
    return rows[0][:w], [r[:w] for r in rows[1:]], name


def read_any(data: bytes, sheet="Mapping", cols="A:AZ"):
    """Chart file (has Mapping sheet) -> Mapping; otherwise first/Combine sheet."""
    wb = openpyxl.load_workbook(BytesIO(data), read_only=True)
    has_mapping = sheet in wb.sheetnames
    wb.close()
    if has_mapping:
        return read_mapping(data, sheet, cols)
    h, b, name = read_table(data, cols)
    return h, b, f"read sheet '{name}'"


# ---------------------------------------------------------------- utils
def key_columns(header):
    """Indexes of SN and TESTNUMBER columns (for duplicate check)."""
    norm = [str(h).strip().upper() if h is not None else "" for h in header]
    try:
        return norm.index("SN"), norm.index("TESTNUMBER")
    except ValueError:
        return None


def keys_of(rows, kc):
    if not kc:
        return set()
    a, b = kc
    return {(str(r[a]), str(r[b])) for r in rows if len(r) > max(a, b) and r[a] is not None}


def same_header(a, b):
    return [str(x) for x in a if x not in (None, "")] == [str(x) for x in b if x not in (None, "")]


def align_to(base, header, rows):
    """Re-order `rows` (with `header`) to the column order of `base` by header name.
    Columns not in base are added at the end. Returns (new_base, aligned_rows, added_names)."""
    base = list(base)

    def nm(h):
        return h.strip().lower() if isinstance(h, str) and h.strip() else None

    src_to_dst, used = {}, set()
    # pass 1: same position and same header (or both unnamed) -> keep position
    for j, h in enumerate(header):
        if j < len(base) and nm(h) == nm(base[j]):
            src_to_dst[j] = j
            used.add(j)
    # pass 2: named columns that moved -> first unused base column with that name
    added = []
    for j, h in enumerate(header):
        if j in src_to_dst or nm(h) is None:
            continue
        hit = next((i for i, b in enumerate(base) if i not in used and nm(b) == nm(h)), None)
        if hit is None:                     # new column name -> add at the end
            hit = len(base)
            base.append(h)
            added.append(str(h))
        src_to_dst[j] = hit
        used.add(hit)
    # unnamed columns that are not at a matching position are dropped
    w = len(base)
    out = []
    for r in rows:
        nr = [None] * w
        for j, d in src_to_dst.items():
            if j < len(r):
                nr[d] = r[j]
        out.append(nr)
    return base, out, added


def dedupe(rows, seen):
    """Drop rows already in `seen` (exact match of all cells); updates `seen`. Returns (kept, n_removed)."""
    kept, n = [], 0
    for r in rows:
        k = tuple(r)
        if k in seen:
            n += 1
            continue
        seen.add(k)
        kept.append(r)
    return kept, n


def safe_sheet_name(name, used=()):
    s = re.sub(r"[\[\]:*?/\\]", "_", str(name))[:31] or "Sheet"
    base, i = s, 2
    while s in used:
        s = f"{base[:28]}_{i}"
        i += 1
    return s


def used_width(header, rows):
    w = max((i + 1 for i, v in enumerate(header) if v not in (None, "")), default=0)
    for r in rows:
        w = max(w, max((i + 1 for i, v in enumerate(r) if v not in (None, "")), default=0))
    return w


def to_xlsx_multi(sheets) -> bytes:
    """sheets: list of (sheet_name, header, rows) -> xlsx bytes (write-only, low memory)."""
    wb = openpyxl.Workbook(write_only=True)
    used = set()
    for name, header, rows in sheets:
        name = safe_sheet_name(name, used)
        used.add(name)
        w = used_width(header, rows)
        ws = wb.create_sheet(name)
        ws.freeze_panes = "A2"
        for i in range(1, w + 1):
            hv = header[i - 1] if i - 1 < len(header) else ""
            ws.column_dimensions[get_column_letter(i)].width = max(10, min(30, len(str(hv or "")) + 4))
        hdr = []
        for v in list(header[:w]) + [None] * (w - len(header[:w])):
            c = WriteOnlyCell(ws, value=v)
            c.font = Font(bold=True)
            hdr.append(c)
        ws.append(hdr)
        for r in rows:
            r = list(r[:w])
            ws.append(r + [None] * (w - len(r)))
    bio = BytesIO()
    wb.save(bio)
    return bio.getvalue()


def to_xlsx(header, rows, sheet_name="Combine") -> bytes:
    """Write header + rows to xlsx bytes (single sheet)."""
    return to_xlsx_multi([(sheet_name, header, rows)])
